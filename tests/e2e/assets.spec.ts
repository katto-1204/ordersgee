import { expect, mockupPng as png, test } from './fixtures'
import type { Page } from '@playwright/test'

async function createOrder(page: Page, name: string, stage: string) {
  await page.goto('/orders')
  await page.getByRole('button', { name: 'New order' }).click()
  await page.getByLabel('Customer / team name').fill(name)
  await page.getByLabel('Current stage').selectOption(stage)
  await page.getByLabel('Artwork approval').selectOption('approved')
  await page.getByRole('button', { name: 'Create order' }).click()
  await page.getByRole('link').filter({ has: page.getByRole('heading', { name, exact: true }) }).click()
  return page.getByRole('dialog', { name, exact: true })
}

test('saves task mockups and print-ready Drive files, validates links and previews after reload', async ({ page }, testInfo) => {
  await page.goto('/tasks')
  await page.getByRole('button', { name: 'New task' }).click()
  await page.getByLabel('Task title').fill('Eagles jersey artwork')
  await page.getByRole('button', { name: 'Create task' }).click()
  await page.getByRole('button', { name: 'Details for Eagles jersey artwork' }).click()
  const dialog = page.getByRole('dialog', { name: 'Task details', exact: true })
  const assets = dialog.getByRole('region', { name: 'Task designs & files' })
  await assets.getByLabel('Task designs & files category').selectOption('print-ready')
  await assets.getByLabel('File name', { exact: true }).fill('Eagles print master')
  await assets.getByLabel('Google Drive file link').fill('https://example.com/unsafe.pdf')
  await assets.getByRole('button', { name: 'Attach Drive file' }).click()
  await expect(assets.getByRole('alert')).toContainText('Use an HTTPS link from drive.google.com or docs.google.com.')
  await assets.getByLabel('Google Drive file link').fill('https://drive.google.com/file/d/eagles-print-master/view')
  await assets.getByRole('button', { name: 'Attach Drive file' }).click()
  await expect(assets.getByRole('link', { name: 'Open in Drive' })).toHaveAttribute('href', 'https://drive.google.com/file/d/eagles-print-master/view')
  await assets.getByLabel('Task designs & files category').selectOption('mockup')
  await assets.getByLabel('Task designs & files upload').setInputFiles({ name: 'eagles-mockup.png', mimeType: 'image/png', buffer: png })
  await expect(assets.getByRole('button', { name: 'Preview eagles-mockup.jpg' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByText('Task saved', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Details for Eagles jersey artwork' }).click()
  await expect(assets.getByText('Eagles print master', { exact: true })).toBeVisible()
  await assets.getByRole('button', { name: 'Preview eagles-mockup.jpg' }).click()
  const preview = page.getByRole('dialog', { name: 'Image preview: eagles-mockup.jpg' })
  await expect(preview.getByRole('img', { name: 'eagles-mockup.jpg' })).toBeVisible()
  await expect.poll(() => preview.getByRole('img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('task-mockup-preview.png'), fullPage: true })
  await preview.getByRole('button', { name: 'Close dialog' }).click()
  await assets.getByRole('button', { name: 'Remove eagles-mockup.jpg' }).click()
  await dialog.getByRole('button', { name: 'Save task' }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Details for Eagles jersey artwork' }).click()
  await expect(assets.getByRole('button', { name: 'Preview eagles-mockup.jpg' })).toHaveCount(0)
  await expect(assets.getByText('Eagles print master', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Complete Eagles jersey artwork' }).click()
  await page.getByRole('button', { name: 'Details for Eagles jersey artwork' }).click()
  await expect(assets.getByText('Eagles print master', { exact: true })).toBeVisible()
})

test('keeps finished and archived teams discoverable with separate mockups and team photos', async ({ page }, testInfo) => {
  const eagles = await createOrder(page, 'Eagles QA', 'finished')
  const eaglesAssets = eagles.getByRole('region', { name: 'Team designs & files' })
  await eaglesAssets.getByLabel('Team designs & files upload').setInputFiles({ name: 'eagles-design.png', mimeType: 'image/png', buffer: png })
  await expect(eaglesAssets.getByRole('button', { name: 'Preview eagles-design.jpg' })).toBeVisible()
  await eaglesAssets.getByLabel('Team designs & files category').selectOption('team-photo')
  await eaglesAssets.getByLabel('Team designs & files upload').setInputFiles({ name: 'eagles-team.png', mimeType: 'image/png', buffer: png })
  await expect(eaglesAssets.getByRole('button', { name: 'Preview eagles-team.jpg' })).toBeVisible()
  await eagles.getByRole('button', { name: 'Close dialog' }).click()

  const foxes = await createOrder(page, 'Foxes QA', 'sizing')
  const foxesAssets = foxes.getByRole('region', { name: 'Team designs & files' })
  await foxesAssets.getByLabel('Team designs & files category').selectOption('team-photo')
  await foxesAssets.getByLabel('Team designs & files upload').setInputFiles({ name: 'foxes-team.png', mimeType: 'image/png', buffer: png })
  await expect(foxesAssets.getByRole('button', { name: 'Preview foxes-team.jpg' })).toBeVisible()
  await expect(foxesAssets.getByRole('button', { name: 'Preview eagles-team.jpg' })).toHaveCount(0)
  await foxes.getByRole('button', { name: 'Archive', exact: true }).click()
  await page.getByRole('button', { name: 'Archive order', exact: true }).click()

  await page.goto('/teams')
  await expect(page.getByRole('heading', { name: 'Team register', exact: true })).toBeVisible()
  const eaglesRecord = page.getByRole('article', { name: 'Eagles QA team record' })
  const foxesRecord = page.getByRole('article', { name: 'Foxes QA team record' })
  await expect(eaglesRecord).toBeVisible()
  await expect(foxesRecord).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expect(eaglesRecord).toContainText('Finished')
  await expect(foxesRecord).toContainText('Archived')
  await page.reload()
  await page.getByLabel('Search team register').fill('QA')
  await expect(eaglesRecord).toBeVisible()
  await expect(foxesRecord).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('team-register.png'), fullPage: true })
  await eaglesRecord.getByRole('link', { name: 'Manage team assets' }).click()
  await expect(eaglesAssets.getByRole('button', { name: 'Preview eagles-design.jpg' })).toBeVisible()
  await expect(eaglesAssets.getByRole('button', { name: 'Preview eagles-team.jpg' })).toBeVisible()
  await expect(eaglesAssets.getByRole('button', { name: 'Preview foxes-team.jpg' })).toHaveCount(0)
  await eagles.getByRole('button', { name: 'Close dialog' }).click()
  await page.goto('/teams')
  await foxesRecord.getByRole('link', { name: 'Manage team assets' }).click()
  await expect(foxesAssets.getByRole('button', { name: 'Preview foxes-team.jpg' })).toBeVisible()
  await expect(foxesAssets.getByRole('button', { name: 'Preview eagles-team.jpg' })).toHaveCount(0)
})
