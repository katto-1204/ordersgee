import { test, expect } from './fixtures'

test('lays out the first-run guide and preserves hide, reopen and navigation', async ({ page }, testInfo) => {
  await page.goto('/')
  const guide = page.getByRole('region', { name: 'Not sure where to begin?' })
  await expect(guide).toBeVisible()
  await expect(guide).toHaveCSS('border-radius', '12px')
  await expect(guide.locator('.getting-started-steps')).toHaveCSS('display', 'grid')
  const title = guide.getByText('Bring in your work', { exact: true })
  const description = guide.getByText('Paste your list with Quick Capture, or create one order.', { exact: true })
  const titleBox = await title.boundingBox()
  const descriptionBox = await description.boundingBox()
  expect(descriptionBox!.y).toBeGreaterThanOrEqual(titleBox!.y + titleBox!.height)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('dashboard-guide.png'), fullPage: true, animations: 'disabled' })
  await guide.getByRole('button', { name: 'Hide this guide' }).click()
  await expect(guide).toHaveCount(0)
  await page.reload()
  await expect(guide).toHaveCount(0)
  await page.getByRole('button', { name: 'Open the GEE TASKS guide' }).click()
  const dialog = page.getByRole('dialog', { name: 'How to use GEE TASKS', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.full-guide-steps > li').first()).toHaveCSS('display', 'grid')
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  const localNote = dialog.locator('.guide-local-note')
  await localNote.scrollIntoViewIfNeeded()
  const noteBox = await localNote.boundingBox()
  const actionsBox = await dialog.locator('.guide-dialog-actions').boundingBox()
  expect(actionsBox!.y).toBeGreaterThanOrEqual(noteBox!.y + noteBox!.height)
  await page.screenshot({ path: testInfo.outputPath('guide-dialog.png'), animations: 'disabled' })
  await dialog.getByRole('link', { name: 'Open production board' }).click()
  await expect(page).toHaveURL('/production')
  await expect(page.getByRole('heading', { name: 'Production board' })).toBeVisible()
})
